/* Generates this sim's authored question files from content/joan-saqs.js — the tool's questions, one file per topic
   under content/joan/: short answers in the format Joan described (a definition plus an example), the multi-choice some
   topics carry, and the drugs she named on 20 Oct (content/joan/drugs.js). Appended as they are; edit those files,
   never the generated output.

   27 Oct 2026: this replaced port-intro-pharm.mjs. The 289 questions it carried across from the intro-pharm hub are
   gone — they pre-dated her formatives and were not in their shape (5–6 mark list questions) — and with them the
   noMock rule that kept the worst of them out of a mock. Her own questions are content/hers.js, read by build.mjs.

   Output: content/authored-mcqs.js + content/authored-saqs.js. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JOAN_SAQS, JOAN_MCQS } from './content/joan-saqs.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));

/* her shape: a short answer is a few lines — a definition and an example, at most a short list */
for (const j of JOAN_SAQS) if (j.steps.length > 4) throw new Error('a written answer runs past 4 points: ' + j.q.slice(0, 90));
const mcqs = JOAN_MCQS.map(m => ({ quiz: m.quiz, quizName: m.quizName, sys: m.sys, q: m.q, options: m.options, correct: m.correct, why: m.why, src: m.src, ...(m.noMock ? { noMock: true } : {}) }));

const head = `/* GENERATED by gen-authored.mjs from content/joan-saqs.js — do not edit by hand.
   None are the lecturer's questions; each names the slide or lecture moment that supplies its answer. */\n`;
fs.writeFileSync(path.join(HERE, 'content/authored-mcqs.js'), head + 'export const AUTHORED_MCQS = ' + JSON.stringify(mcqs, null, 1) + ';\n');
fs.writeFileSync(path.join(HERE, 'content/authored-saqs.js'), head + 'export const AUTHORED_SAQS = ' + JSON.stringify(JOAN_SAQS, null, 1) + ';\n');
console.log(`generated ${mcqs.length} multi-choice + ${JOAN_SAQS.length} written (the tool's)`);
