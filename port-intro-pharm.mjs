/* Port intro-pharm's authored question sets into this sim's authored format.
   Source: bank/intro-pharm.json — lifted untouched out of ../intro-pharm/index.html
   (const DATA) by the estate's extract step; 189 written + 100 multi-choice, every one
   written from the 14 lecture decks and naming the slide that supplies its answer.

   Nothing is rewritten here. q, options, key, why, model-answer lines, marks and src are
   carried across as they are; this file only adds the quiz row (one per topic) and the
   group each topic belongs to (TOPIC_SYS below — must agree with META.sys).
   Output: content/authored-mcqs.js + content/authored-saqs.js (generated — edit the
   source, not these). */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(HERE, 'bank/intro-pharm.json'), 'utf8'));

/* topic id -> [group, quiz-row name]; order here is the order of the rows on the page */
export const TOPIC_SYS = {
  concepts1: ['found', 'M1 · What pharmacology is'],
  concepts2: ['found', 'M1 · Drug names, sources & schedules'],
  calcs:     ['calc',  'M2 · Medication calculations'],
  pk1:       ['pkpd',  'M3 · Pharmacokinetics (1)'],
  pk2:       ['pkpd',  'M3 · Pharmacokinetics (2)'],
  pd:        ['pkpd',  'M4 · Pharmacodynamics'],
  admin:     ['admin', 'M5 · Medication administration'],
  educ:      ['admin', 'M5 · Patient education'],
  elderly:   ['life',  'M6 · The older adult'],
  lifespan:  ['life',  'M6 · Across the lifespan'],
  legal:     ['law',   'M7 · Legal & ethical'],
  devmkt:    ['law',   'M7 · Drug development & marketing'],
  allergy:   ['imm',   'M8 · Anaphylaxis (ASCIA plan)'],
};

const mcqs = [], saqs = [];
for (const t of src.topics) {
  const row = TOPIC_SYS[t.id];
  if (!row) throw new Error('intro-pharm topic with no TOPIC_SYS row: ' + t.id);
  const [sys, quizName] = row;
  for (const m of t.mcq) mcqs.push({ quiz: t.id, quizName, sys, q: m.q, options: m.options, correct: m.correct, why: m.why, src: m.src });
  for (const r of t.recall) saqs.push({ quiz: t.id, quizName, sys, q: r.q, steps: r.a, pts: r.marks, src: r.src });
}
for (const id of Object.keys(TOPIC_SYS)) if (!src.topics.some(t => t.id === id)) throw new Error('TOPIC_SYS row matches no intro-pharm topic: ' + id);

const head = (what) => `/* GENERATED by port-intro-pharm.mjs from bank/intro-pharm.json — do not edit by hand.
   ${what} written by the intro-pharm hub from the 14 lecture decks (not the lecturer's
   questions); each names the slide that supplies its answer. */\n`;
fs.writeFileSync(path.join(HERE, 'content/authored-mcqs.js'), head('Multi-choice questions') + 'export const AUTHORED_MCQS = ' + JSON.stringify(mcqs, null, 1) + ';\n');
fs.writeFileSync(path.join(HERE, 'content/authored-saqs.js'), head('Written questions and their model answers') + 'export const AUTHORED_SAQS = ' + JSON.stringify(saqs, null, 1) + ';\n');
console.log(`ported ${mcqs.length} multi-choice + ${saqs.length} written across ${src.topics.length} topics`);
