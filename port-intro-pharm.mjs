/* Generates this sim's authored question files from its TWO sources:

   1. bank/intro-pharm.json — lifted untouched out of ../intro-pharm/index.html (const DATA)
      by the estate's extract step; 189 written + 100 multi-choice, every one written from the
      14 lecture decks and naming the slide that supplies its answer. Nothing is rewritten
      here: q, options, key, why, model-answer lines, marks and src are carried across as they
      are; this file only adds the quiz row (one per topic), the group each topic belongs to
      (TOPIC_SYS below — must agree with META.sys) and the noMock flag (rule below).
   2. content/joan-saqs.js — HAND-WRITTEN short answers in the format Joan described on
      16 Sep 2026 (a definition plus an example, 3–4 lines, no specific-drug questions).
      Appended as they are. Edit those files, never the generated output.

   Output: content/authored-mcqs.js + content/authored-saqs.js (generated — edit the
   sources, not these). Pass --list to print every question the noMock rule catches. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JOAN_SAQS } from './content/joan-saqs.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(HERE, 'bank/intro-pharm.json'), 'utf8'));

/* topic id -> [group, quiz-row name]; order here is the order of the rows on the page */
export const TOPIC_SYS = {
  concepts1: ['found', 'M1 · What pharmacology is'],
  concepts2: ['found', 'M1 · Drug names, sources & schedules'],
  calcs:     ['calc',  'M2 · Medication calculations'],
  pk1:       ['pkpd',  'M3 · Pharmacokinetics (1)'],
  pk2:       ['pkpd',  'M3 · Pharmacokinetics (2)'],
  pd:        ['pkpd',  'M4 · Pharmacodynamics'],
  admin:     ['admin', 'M5 · Medication administration'],
  educ:      ['admin', 'M5 · Patient education'],
  elderly:   ['life',  'M6 · The older adult'],
  lifespan:  ['life',  'M6 · Across the lifespan'],
  legal:     ['law',   'M7 · Legal & ethical'],
  devmkt:    ['law',   'M7 · Drug development & marketing'],
  allergy:   ['imm',   'M8 · Anaphylaxis (ASCIA plan)'],
};

/* ── noMock: which intro-pharm WRITTEN questions a mock paper must not deal ──
   Joan, 16 Sep 2026: a short answer is a definition plus an example in 3–4 lines, and she
   will not ask about specific drugs. intro-pharm's written questions pre-date that. They all
   stay drillable under Pick my rep and Learn; a mock, which claims the paper's shape, leaves
   out any whose STEM:
     long   carries 4 or more marks — "name the four…", "compare…", "give six…": a list
            question, not a definition and an example in 3–4 lines;
     drug   names a specific drug or substance (the list below — read from all 189 stems);
     recall asks for "the lecture's example(s)" — those examples are named drugs;
     calc   is a worked calculation (the calcs topic, with a quantity in it) — medication
            calculations are their own assessment, and a calculation is not a definition.
   Every hit was read by hand on 19 Sep 2026 (`node port-intro-pharm.mjs --list`). Multi-choice
   questions are untouched: she gave no such rule for them. */
const DRUG = /\b(paracetamol|aspirin|digoxin|furosemide|ampicillin|prednisone|adrenaline|morphine|amoxicillin|methadone|alcohol|nicotine|cannabis|caffeine|opioid)\b/i;
const RECALL = /lecture['’]s (?:\w+[- ])?examples?\b|lecture['’]s two examples|\bfrom the lecture\b/i;
const QUANTITY = /\d\s?(?:mg|mcg|g|mL|L|kg|gtt|drops|hours)\b|\b1:1000\b/;
const noMockWhy = (topic, r) =>
  r.marks >= 4 ? 'long' : DRUG.test(r.q) ? 'drug' : RECALL.test(r.q) ? 'recall' : (topic === 'calcs' && QUANTITY.test(r.q)) ? 'calc' : null;

const mcqs = [], saqs = [], hits = [];
for (const t of src.topics) {
  const row = TOPIC_SYS[t.id];
  if (!row) throw new Error('intro-pharm topic with no TOPIC_SYS row: ' + t.id);
  const [sys, quizName] = row;
  for (const m of t.mcq) mcqs.push({ quiz: t.id, quizName, sys, q: m.q, options: m.options, correct: m.correct, why: m.why, src: m.src });
  for (const r of t.recall) {
    const why = noMockWhy(t.id, r);
    if (why) hits.push(`${why.padEnd(6)} ${t.id.padEnd(9)} ${r.marks}mk  ${r.q.replace(/\s+/g, ' ').slice(0, 120)}`);
    saqs.push({ quiz: t.id, quizName, sys, q: r.q, steps: r.a, pts: r.marks, src: r.src, ...(why ? { noMock: true } : {}) });
  }
}
for (const id of Object.keys(TOPIC_SYS)) if (!src.topics.some(t => t.id === id)) throw new Error('TOPIC_SYS row matches no intro-pharm topic: ' + id);
const nIntro = saqs.length;

/* the hand-written Joan-format questions: never noMock, and a drug in a STEM fails the port */
for (const j of JOAN_SAQS) {
  if (DRUG.test(j.q)) throw new Error('a Joan-format stem names a specific drug: ' + j.q.slice(0, 90));
  if (j.steps.length > 4) throw new Error('a Joan-format answer runs past 4 points: ' + j.q.slice(0, 90));
  saqs.push(j);
}

const head = (what) => `/* GENERATED by port-intro-pharm.mjs — do not edit by hand. Two sources:
   bank/intro-pharm.json (${what} written by the intro-pharm hub from the 14 lecture decks) and,
   for written questions, content/joan-saqs.js (hand-written in Joan's stated exam format).
   None are the lecturer's questions; each names the slide or lecture moment that supplies its answer. */\n`;
fs.writeFileSync(path.join(HERE, 'content/authored-mcqs.js'), head('multi-choice questions') + 'export const AUTHORED_MCQS = ' + JSON.stringify(mcqs, null, 1) + ';\n');
fs.writeFileSync(path.join(HERE, 'content/authored-saqs.js'), head('written questions and model answers') + 'export const AUTHORED_SAQS = ' + JSON.stringify(saqs, null, 1) + ';\n');
if (process.argv.includes('--list')) console.log(hits.join('\n'));
console.log(`ported ${mcqs.length} multi-choice + ${nIntro} written across ${src.topics.length} topics (${hits.length} written kept out of the mock) + ${JOAN_SAQS.length} written in Joan's format`);
